import type { ChangeOp } from '../diff/ops';
import { orderOps } from '../order/order';
import { assessRisk, RISK_LABELS, type RiskLevel } from '../risk/assess';
import { renderColumnOp } from './columns';
import { renderCommentOp } from './comments';
import { renderConstraintOp } from './constraints';
import { renderIndexOp } from './indexes';
import type { RenderContext } from './names';
import { renderSchemaOp } from './schemas';
import { renderTableOp } from './tables';

/** Everything the migration text can depend on. It never reads the clock or the database. */
export interface MigrationContext extends RenderContext {
  /** Passed in, so the same changes always give the same text. */
  generatedAt: string;
  dbName: string;
}

export interface Migration {
  /** The whole file: header, `BEGIN;`, every statement, `COMMIT;`. */
  text: string;
  /** The statements alone, in order, without `;`, `BEGIN` or `COMMIT`: what Validate runs. */
  statements: string[];
}

function renderOp(op: ChangeOp, context: MigrationContext): string[] {
  switch (op.kind) {
    case 'createSchema':
      return renderSchemaOp(op);
    case 'createTable':
    case 'renameTable':
    case 'dropTable':
      return renderTableOp(op, context);
    case 'addColumn':
    case 'renameColumn':
    case 'alterColumnType':
    case 'setNotNull':
    case 'dropNotNull':
    case 'setDefault':
    case 'dropDefault':
    case 'dropColumn':
      return renderColumnOp(op, context);
    case 'addConstraint':
    case 'renameConstraint':
    case 'dropConstraint':
      return renderConstraintOp(op, context);
    case 'addIndex':
    case 'renameIndex':
    case 'dropIndex':
      return renderIndexOp(op, context);
    case 'setComment':
      return renderCommentOp(op, context);
    default: {
      const unreachable: never = op;
      return unreachable;
    }
  }
}

/** A value written into a `--` comment must not be able to end the line and start SQL. */
const oneLine = (text: string): string =>
  text.replace(/[\r\n\u2028\u2029]+/g, ' ');

const LEVELS = Object.keys(RISK_LABELS) as RiskLevel[];

/**
 * The migration for these changes: header, then every statement in phase order inside one
 * transaction. A statement whose operation is risky has a `-- WARNING` line above it for each
 * risk, and the header counts the risks by level. The same operations, models and context always
 * give the same text.
 */
export function renderMigration(
  ops: ChangeOp[],
  context: MigrationContext,
): Migration {
  const steps = orderOps(ops, context).map(({ op }) => ({
    statements: renderOp(op, context),
    risks: assessRisk(op, context.baseline),
  }));
  const statements = steps.flatMap((step) => step.statements);

  const risks = steps.flatMap((step) => step.risks);
  const counts = LEVELS.flatMap((level) => {
    const count = risks.filter((r) => r.level === level).length;
    return count > 0 ? [`${count} ${RISK_LABELS[level]}`] : [];
  });
  const header = [
    '-- Generated by pgsketch',
    `-- Generated at: ${oneLine(context.generatedAt)}`,
    `-- Database: ${oneLine(context.dbName)}`,
    `-- Operations: ${ops.length}`,
    `-- Risks: ${counts.length > 0 ? counts.join(', ') : 'none'}`,
  ];
  // the warnings go above the first statement of their operation; messages can contain object names
  const body = steps.flatMap(({ statements: own, risks: warned }) =>
    own.flatMap((statement, i) => [
      ...(i === 0
        ? warned.map(
            (r) =>
              `-- WARNING (${RISK_LABELS[r.level]}): ${oneLine(r.message)}`,
          )
        : []),
      `${statement};`,
      '',
    ]),
  );
  return {
    text: [...header, '', 'BEGIN;', '', ...body, 'COMMIT;', ''].join('\n'),
    statements,
  };
}
