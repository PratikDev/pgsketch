import type { Column } from '../model/types';
import { renderPgType } from '../sql/pgtype';
import { quoteIdent } from '../sql/quote';

/**
 * A column as it appears in `CREATE TABLE` or `ADD COLUMN`. An identity column is NOT NULL by
 * itself, so that is left out. The default is the expression text the database normalized, not
 * something built from user input here.
 */
export function columnDefinition(column: Column): string {
  const parts = [quoteIdent(column.name), renderPgType(column.type)];
  if (column.identity === 'always') parts.push('GENERATED ALWAYS AS IDENTITY');
  if (column.identity === 'byDefault')
    parts.push('GENERATED BY DEFAULT AS IDENTITY');
  if (column.notNull && !column.identity) parts.push('NOT NULL');
  if (column.default) parts.push(`DEFAULT ${column.default.expression}`);
  return parts.join(' ');
}
