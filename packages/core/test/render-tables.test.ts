import { describe, expect, test } from 'vitest';
import type { ChangeOp } from '../src/diff/ops';
import type {
  Column,
  Constraint,
  ModelPair,
  SchemaModel,
} from '../src/model/types';
import { renderTableOp } from '../src/render/tables';
import { fixtureModel as m } from './fixtures/model';

const models: ModelPair = { baseline: m, desired: m };

const column = (
  id: string,
  name: string,
  over: Partial<Column> = {},
): Column => ({
  id,
  tableId: 'new-t',
  name,
  position: 1,
  type: { name: 'text', isArray: false },
  notNull: false,
  default: null,
  identity: null,
  comment: null,
  ...over,
});
const pk = (name: string, columnIds: string[]): Constraint => ({
  id: 'new-pk',
  tableId: 'new-t',
  kind: 'pk',
  name,
  columnIds,
});
const create = (
  name: string,
  columns: Column[],
  primaryKey?: Constraint,
  schemaId = 's:1',
): ChangeOp => ({
  kind: 'createTable',
  table: { id: 'new-t', schemaId, name, comment: null },
  columns,
  ...(primaryKey && { pk: primaryKey }),
});
const render = (op: ChangeOp, pair = models) =>
  renderTableOp(op as Parameters<typeof renderTableOp>[0], pair);

describe('create', () => {
  test('a table with an identity primary key', () => {
    const op = create(
      'users',
      [
        column('a', 'id', {
          type: { name: 'bigint', isArray: false },
          identity: 'always',
          notNull: true,
        }),
        column('b', 'email', { notNull: true }),
        column('c', 'age', {
          type: { name: 'integer', isArray: false },
          default: { kind: 'constant', expression: '18' },
        }),
      ],
      pk('users_pkey', ['a']),
    );
    expect(render(op)).toEqual([
      `CREATE TABLE "public"."users" (
  "id" bigint GENERATED ALWAYS AS IDENTITY,
  "email" text NOT NULL,
  "age" integer DEFAULT 18,
  CONSTRAINT "users_pkey" PRIMARY KEY ("id")
)`,
    ]);
  });

  test('identity BY DEFAULT, and a composite primary key in the order given', () => {
    const op = create(
      'pairs',
      [
        column('a', 'left', { notNull: true }),
        column('b', 'right', { notNull: true }),
        column('c', 'id', {
          type: { name: 'integer', isArray: false },
          identity: 'byDefault',
          notNull: true,
        }),
      ],
      pk('pairs_pkey', ['b', 'a']),
    );
    expect(render(op)[0]).toBe(`CREATE TABLE "public"."pairs" (
  "left" text NOT NULL,
  "right" text NOT NULL,
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  CONSTRAINT "pairs_pkey" PRIMARY KEY ("right", "left")
)`);
  });

  test('a table without a primary key has none', () => {
    expect(render(create('log', [column('a', 'message')]))).toEqual([
      `CREATE TABLE "public"."log" (\n  "message" text\n)`,
    ]);
  });

  test('types: parameters, arrays and schema-qualified user types', () => {
    const op = create('typed', [
      column('a', 'name', {
        type: { name: 'varchar', params: [255], isArray: false },
      }),
      column('b', 'price', {
        type: { name: 'numeric', params: [10, 2], isArray: false },
      }),
      column('c', 'tags', { type: { name: 'text', isArray: true } }),
      column('d', 'feeling', {
        type: { name: 'mood', schema: 'public', isArray: false },
      }),
      column('e', 'at', {
        type: { name: 'timestamptz', isArray: false },
        default: { kind: 'preset', preset: 'now', expression: 'now()' },
      }),
    ]);
    expect(render(op)[0]).toBe(`CREATE TABLE "public"."typed" (
  "name" varchar(255),
  "price" numeric(10,2),
  "tags" text[],
  "feeling" "public"."mood",
  "at" timestamptz DEFAULT now()
)`);
  });

  test('names are quoted whatever they contain', () => {
    const op = create(
      'My "Table"',
      [column('a', 'order', { notNull: true })],
      pk('My "Table"_pkey', ['a']),
      's:2',
    );
    expect(render(op)[0]).toBe(`CREATE TABLE "billing"."My ""Table""" (
  "order" text NOT NULL,
  CONSTRAINT "My ""Table""_pkey" PRIMARY KEY ("order")
)`);
  });

  test('the schema can be one created in the same migration', () => {
    const desired: SchemaModel = structuredClone(m);
    desired.schemas['new-s'] = { id: 'new-s', name: 'fresh' };
    expect(
      render(create('t', [column('a', 'x')], undefined, 'new-s'), {
        baseline: m,
        desired,
      })[0],
    ).toContain('"fresh"."t"');
  });

  test('a table in an unknown schema is an error, not guessed SQL', () => {
    expect(() =>
      render(create('t', [column('a', 'x')], undefined, 'missing')),
    ).toThrow('Unknown schema');
  });
});

describe('rename and drop', () => {
  test("rename uses the table's schema and the new name unqualified", () => {
    expect(
      render({
        kind: 'renameTable',
        tableId: 't:20',
        from: 'invoices',
        to: 'bills',
      }),
    ).toEqual(['ALTER TABLE "billing"."invoices" RENAME TO "bills"']);
  });

  test('rename quotes odd names', () => {
    expect(
      render({
        kind: 'renameTable',
        tableId: 't:10',
        from: 'us"ers',
        to: 'select',
      }),
    ).toEqual(['ALTER TABLE "public"."us""ers" RENAME TO "select"']);
  });

  test('drop has no CASCADE', () => {
    expect(render({ kind: 'dropTable', table: m.tables['t:20'] })).toEqual([
      'DROP TABLE "billing"."invoices"',
    ]);
  });

  test('renaming a table that is not in the loaded schema is an error', () => {
    expect(() =>
      render({ kind: 'renameTable', tableId: 'nope', from: 'a', to: 'b' }),
    ).toThrow('Unknown table');
  });
});
