import { afterAll, beforeAll, expect, test } from 'vitest';
import { introspectColumns } from '../src/introspect/columns';
import { withSnapshot } from '../src/introspect/query';
import { oidOf, startPostgres, type TestPostgres } from './pg';

let pg: TestPostgres;
const isPg18 = () => Number(pg.version) >= 18;

beforeAll(async () => {
  pg = await startPostgres();
  await pg.query(`
    CREATE TYPE public.mood AS ENUM ('happy');
    CREATE TABLE public.t (
      id bigint GENERATED ALWAYS AS IDENTITY,
      alt_id integer GENERATED BY DEFAULT AS IDENTITY,
      name varchar(255) NOT NULL DEFAULT 'x',
      created timestamptz DEFAULT now(),
      price numeric(10,2),
      tags text[],
      feeling public.mood,
      doubled integer GENERATED ALWAYS AS (price::integer * 2) STORED,
      dropped_soon text,
      note text
    );
    COMMENT ON COLUMN public.t.note IS 'a "note"';
    ALTER TABLE public.t DROP COLUMN dropped_soon;
    CREATE TABLE public.legacy (id serial PRIMARY KEY, label text);
    CREATE TABLE public.events (id int, day date NOT NULL) PARTITION BY RANGE (day);
    CREATE TABLE public.events_2024 PARTITION OF public.events
      FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
    CREATE VIEW public.a_view AS SELECT 1 AS v;
  `);
});

afterAll(async () => {
  await pg?.stop();
});

const columnsOf = async (table: string) => {
  const all = await withSnapshot(pg.query, () => introspectColumns(pg.query));
  const oid = await oidOf(pg.query, `'${table}'::regclass::oid`);
  return Object.fromEntries(
    all.filter((c) => c.tableId === `t:${oid}`).map((c) => [c.name, c]),
  );
};

test('one column per feature, compared field by field', async () => {
  const c = await columnsOf('public.t');
  expect(c.name).toMatchObject({
    type: { name: 'varchar', params: [255], isArray: false },
    notNull: true,
    default: { kind: 'expression', expression: "'x'::character varying" },
    identity: null,
    comment: null,
  });
  expect(c.created).toMatchObject({
    type: { name: 'timestamptz', isArray: false },
    notNull: false,
    default: { kind: 'expression', expression: 'now()' },
  });
  expect(c.price!.type).toEqual({
    name: 'numeric',
    params: [10, 2],
    isArray: false,
  });
  expect(c.tags!.type).toEqual({ name: 'text', isArray: true });
  expect(c.feeling!.type).toEqual({
    name: 'mood',
    schema: 'public',
    isArray: false,
  });
  expect(c.note!.comment).toBe('a "note"');
});

test('identity ALWAYS and BY DEFAULT are distinguished, and have no default', async () => {
  const c = await columnsOf('public.t');
  expect(c.id).toMatchObject({
    identity: 'always',
    default: null,
    notNull: true,
  });
  expect(c.alt_id).toMatchObject({
    identity: 'byDefault',
    default: null,
    notNull: true,
  });
  expect(c.name!.identity).toBeNull();
});

test('a generated column is read-only', async () => {
  const c = await columnsOf('public.t');
  expect(c.doubled!.readOnly).toBe('generated-column');
  expect(c.price).not.toHaveProperty('readOnly');
});

test('a serial column keeps its nextval default and is read-only', async () => {
  const c = await columnsOf('public.legacy');
  expect(c.id!.readOnly).toBe('nextval-default');
  expect(c.id!.default!.expression).toBe(
    "nextval('public.legacy_id_seq'::regclass)",
  );
  expect(c.label).not.toHaveProperty('readOnly');
});

test('dropped columns are skipped and attnum gaps are kept as positions', async () => {
  const c = await columnsOf('public.t');
  expect(c.dropped_soon).toBeUndefined();
  expect(c.note!.position).toBe(10);
  expect(c.feeling!.position).toBe(7);
});

test('columns of a read-only table are read-only for the table reason', async () => {
  expect((await columnsOf('public.events')).day!.readOnly).toBe(
    'partitioned-table',
  );
  expect((await columnsOf('public.events_2024')).day!.readOnly).toBe(
    'partition',
  );
});

test('columns of views are not returned', async () => {
  const all = await withSnapshot(pg.query, () => introspectColumns(pg.query));
  expect(all.some((c) => c.name === 'v')).toBe(false);
});

test.skipIf(Number(process.env.PG_VERSION ?? '16') < 18)(
  'Postgres 18: a NOT VALID NOT NULL makes the column read-only',
  async () => {
    expect(isPg18()).toBe(true);
    await pg.query(`
      CREATE TABLE public.nn (a int, b int);
      ALTER TABLE public.nn ADD CONSTRAINT a_nn NOT NULL a NOT VALID;
    `);
    const c = await columnsOf('public.nn');
    expect(c.a!.readOnly).toBe('not-null-not-valid');
    expect(c.b).not.toHaveProperty('readOnly');
  },
);
