import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, test, type Page } from '@playwright/test';
import { launchApp } from './app';
import { rowOf, showTable, startScratchServer } from './canvas';
import { connectThroughForm } from './form';
import { E2E_PASSWORD, E2E_USER } from './server';

/** Renames column `b` of `public.scratch` to `bb`. */
async function edit(window: Page) {
  await showTable(window, 'public.scratch');
  await rowOf(window, 'public.scratch', 'b')
    .getByRole('button', { name: 'b', exact: true })
    .click();
  await window.keyboard.type('bb');
  await window.keyboard.press('Tab');
}

/** An editor on a server of its own with `public.scratch` (a, b) and a row whose `a` is null, with column `b` renamed and the SQL open. */
async function editorWithRename() {
  const server = await startScratchServer();
  // the app connects as the e2e user, who has to own the table to alter it
  await server.admin.query(`ALTER TABLE public.scratch OWNER TO ${E2E_USER}`);
  await server.admin.query('INSERT INTO public.scratch (id) VALUES (1)');
  const { app, window } = await launchApp();
  await connectThroughForm(window, server, E2E_PASSWORD);
  await expect(window.locator('[data-layout="ready"]')).toHaveCount(1);
  await edit(window);
  await window.getByRole('button', { name: 'Generate SQL' }).click();
  const panel = window.getByRole('region', { name: 'SQL' });
  await expect(panel.locator('.cm-content')).toContainText(
    'RENAME COLUMN "b" TO "bb"',
  );
  return { app, window, server, panel };
}

const columnNames = async (
  server: Awaited<ReturnType<typeof startScratchServer>>,
) =>
  (
    await server.admin.query<{ column_name: string }>(
      `SELECT column_name FROM information_schema.columns WHERE table_name = 'scratch' ORDER BY ordinal_position`,
    )
  ).rows.map((r) => r.column_name);

test('Copy puts the SQL on the clipboard', async () => {
  test.setTimeout(120_000);
  const { app, server, panel } = await editorWithRename();
  try {
    await panel.getByRole('button', { name: 'Copy' }).click();
    await expect(panel.getByRole('button', { name: 'Copied' })).toBeVisible();
    const copied = () => app.evaluate(({ clipboard }) => clipboard.readText());
    await expect.poll(copied).toMatch(/^-- Generated by pgsketch/);
    expect(await copied()).toContain('RENAME COLUMN "b" TO "bb"');
    expect(await copied()).toMatch(/COMMIT;\s*$/);
  } finally {
    await app.close();
    await server.stop();
  }
});

test('Save writes the SQL where the dialog says, and the next save opens in that folder', async () => {
  test.setTimeout(120_000);
  const { app, window, server, panel } = await editorWithRename();
  try {
    // the native dialog can't be driven, so it answers with a file in a folder of the test's making
    const folder = mkdtempSync(join(tmpdir(), 'pgsketch-save-'));
    await app.evaluate(({ dialog }, dir) => {
      const opened: string[] = [];
      Object.assign(globalThis, { savedWhere: opened });
      dialog.showSaveDialog = (async (...args: unknown[]) => {
        const options = args[args.length - 1] as { defaultPath: string };
        opened.push(options.defaultPath);
        return { canceled: false, filePath: `${dir}/migration.sql` };
      }) as typeof dialog.showSaveDialog;
    }, folder);
    await panel.getByRole('button', { name: 'Save' }).click();
    await expect(
      window.getByText(`Saved ${folder}/migration.sql`),
    ).toBeVisible();
    await panel.getByRole('button', { name: 'Save' }).click();
    await expect
      .poll(() =>
        app.evaluate(
          () => (globalThis as { savedWhere?: string[] }).savedWhere ?? [],
        ),
      )
      .toHaveLength(2);
    const [first, second] = await app.evaluate(
      () => (globalThis as { savedWhere?: string[] }).savedWhere ?? [],
    );
    expect(first).toMatch(/\/\d{8}_\d{6}_pgsketch\.sql$/);
    expect(second?.startsWith(folder)).toBe(true);
    expect(readFileSync(`${folder}/migration.sql`, 'utf8')).toContain(
      'RENAME COLUMN "b" TO "bb"',
    );
  } finally {
    await app.close();
    await server.stop();
  }
});

test('Validate shows a result for each statement and keeps nothing', async () => {
  test.setTimeout(120_000);
  const { app, window, server, panel } = await editorWithRename();
  try {
    await panel.getByRole('button', { name: 'Validate' }).click();
    const results = window.getByRole('region', { name: 'Validation results' });
    await expect(results.getByRole('status')).toHaveText(
      'All 1 statement passed. Nothing was kept.',
    );
    await expect(results.getByLabel('Passed')).toBeVisible();
    // a dry run: the column is still called b
    expect(await columnNames(server)).toEqual(['id', 'a', 'b']);

    // a second edit that the data can't take: a is null in the row
    await rowOf(window, 'public.scratch', 'a')
      .getByRole('button', { name: /^NN/ })
      .click();
    await expect(results).toHaveCount(0); // the SQL changed, so the old results went
    await panel.getByRole('button', { name: 'Validate' }).click();
    await expect(results.getByRole('status')).toHaveText(
      'Statement 2 of 2 failed. Nothing was kept.',
    );
    await expect(results.getByRole('alert')).toContainText('(23502)');
    await expect(results.getByLabel('Passed')).toHaveCount(1);
    expect(await columnNames(server)).toEqual(['id', 'a', 'b']);
  } finally {
    await app.close();
    await server.stop();
  }
});

test('a server that is not this machine is asked about first', async () => {
  test.setTimeout(120_000);
  const server = await startScratchServer();
  const { app, window } = await launchApp();
  try {
    // 127.0.0.2 is this machine too, but not a name the app knows as local
    await window.getByLabel('Host').fill('127.0.0.2');
    await window.getByRole('combobox', { name: 'SSL mode' }).click();
    await window.getByRole('option', { name: 'disable' }).click();
    await window.getByLabel('Port').fill(String(server.port));
    await window.getByLabel('User').fill(E2E_USER);
    await window.getByLabel('Password', { exact: true }).fill(E2E_PASSWORD);
    await window.getByLabel('Database').fill(server.database);
    await window.getByRole('button', { name: 'Connect' }).click();
    await expect(window.locator('[data-layout="ready"]')).toHaveCount(1);
    await edit(window);
    await window.getByRole('button', { name: 'Generate SQL' }).click();
    const panel = window.getByRole('region', { name: 'SQL' });
    await expect(panel.locator('.cm-content')).toContainText('RENAME COLUMN');

    await panel.getByRole('button', { name: 'Validate' }).click();
    const dialog = window.getByRole('dialog');
    await expect(dialog).toContainText('Validate on 127.0.0.2?');
    await expect(
      window.getByRole('region', { name: 'Validation results' }),
    ).toHaveCount(0);
    await dialog.getByRole('button', { name: 'Cancel' }).click();
    await expect(dialog).toHaveCount(0);

    await panel.getByRole('button', { name: 'Validate' }).click();
    await window
      .getByRole('dialog')
      .getByRole('button', { name: 'Validate' })
      .click();
    await expect(
      window.getByRole('region', { name: 'Validation results' }),
    ).toBeVisible();
  } finally {
    await app.close();
    await server.stop();
  }
});
