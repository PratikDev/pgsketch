import { act, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import type { SchemaModel } from '@pgsketch/core';
import { afterEach, beforeEach, describe, expect, test, vi } from 'vitest';
import { schemaStore } from '@/stores/schema';
import { uiStore } from '@/stores/ui';
import { fixtureModel } from '@/test-model';
import { installFakeApi } from '@/test-utils';
import { SqlPanel } from './SqlPanel';

const casts = { categories: {}, domains: {}, casts: {} };
const load = (model: SchemaModel = fixtureModel, fingerprint = 'f0') =>
  act(() => schemaStore.getState().load({ model, casts, fingerprint }));

/** A database whose fingerprint is whatever `database.fingerprint` is. */
function setup(onSchemaChanged: () => Promise<void> = async () => undefined) {
  const database = { fingerprint: 'f0' };
  const calls = installFakeApi({
    'schema.fingerprint': () => database.fingerprint,
    'schema.casts': () => casts,
  });
  render(<SqlPanel dbName="app" onSchemaChanged={onSchemaChanged} />);
  return {
    database,
    calls,
    channel: (c: string) => calls.filter((x) => x.channel === c),
  };
}
const sqlText = () =>
  [...document.querySelectorAll('.cm-line')]
    .map((l) => l.textContent)
    .join('\n');

beforeEach(() => load());
afterEach(() =>
  act(() => {
    uiStore.getState().setConnectionLost(null);
    uiStore.getState().setSqlPanelOpen(false);
  }),
);

describe('SqlPanel', () => {
  test('shows the SQL of the edits, after checking that the database is as it was loaded', async () => {
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    const { channel } = setup();
    expect(screen.getByText('Generating…')).toBeInTheDocument();
    await waitFor(() => expect(sqlText()).toMatch(/RENAME TO "people"/));
    expect(sqlText()).toMatch(/-- Database: app/);
    expect(sqlText()).toMatch(/^-- Generated by pgsketch/);
    expect(channel('schema.fingerprint')).toHaveLength(1);
    // fresh cast data, read when the SQL is made
    expect(channel('schema.casts')).toHaveLength(1);
    // a rename can break code that uses the old name
    expect(
      screen.getByRole('button', { name: /breaks app code/ }),
    ).toBeInTheDocument();
  });

  test('summarizes the risks of what it generates', async () => {
    act(() => schemaStore.getState().removeColumn('c:20:2'));
    setup();
    expect(
      await screen.findByRole('button', { name: /destructive/ }),
    ).toBeInTheDocument();
    await waitFor(() => expect(sqlText()).toMatch(/WARNING \(destructive\)/));
  });

  test('makes the SQL again when the edits change while it is open', async () => {
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    setup();
    await waitFor(() => expect(sqlText()).toMatch(/"people"/));
    act(() => schemaStore.getState().renameTable('t:10', 'persons'));
    await waitFor(() => expect(sqlText()).toMatch(/"persons"/));
    expect(sqlText()).not.toMatch(/"people"/);
    // down to nothing: nothing to generate, and it says so
    act(() => schemaStore.getState().renameTable('t:10', 'users'));
    expect(
      await screen.findByText(/no changes to generate/),
    ).toBeInTheDocument();
  });

  test('says what blocks it instead of generating: no changes, an error, a lost connection', async () => {
    setup();
    expect(
      await screen.findByText(/no changes to generate/),
    ).toBeInTheDocument();
    act(() => schemaStore.getState().renameTable('t:10', ''));
    expect(await screen.findByText(/Fix this first/)).toBeInTheDocument();
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    await waitFor(() => expect(sqlText()).toMatch(/"people"/));
    act(() => uiStore.getState().setConnectionLost('gone'));
    expect(
      await screen.findByText(/connection to the database was lost/),
    ).toBeInTheDocument();
  });

  test('when the database is not as it was loaded, it asks for the change to be looked at, and generates nothing meanwhile', async () => {
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    const looked = vi.fn(async () => undefined);
    const { database, channel } = setup(looked);
    // (the first check passes: the fingerprint is as loaded)
    await waitFor(() => expect(sqlText()).toMatch(/"people"/));
    database.fingerprint = 'f1';
    act(() => schemaStore.getState().renameTable('t:10', 'persons'));
    await waitFor(() => expect(looked).toHaveBeenCalledOnce());
    // the handler left things as they were and the database still differs: nothing is generated,
    // and the casts were not asked for again
    expect(
      await screen.findByText(/change is not taken yet/),
    ).toBeInTheDocument();
    expect(channel('schema.casts')).toHaveLength(1);
    expect(document.querySelector('.cm-editor')).toBeNull();
  });

  test('a change that goes stale blocks it, and an unrelated external change never lets SQL through', async () => {
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    const { database } = setup(async () => schemaStore.getState().markStale());
    await waitFor(() => expect(sqlText()).toMatch(/"people"/));
    database.fingerprint = 'f1';
    act(() => schemaStore.getState().renameTable('t:10', 'persons'));
    expect(
      await screen.findByText(/changed outside pgsketch/),
    ).toBeInTheDocument();
    expect(document.querySelector('.cm-editor')).toBeNull();
  });

  test('an applied migration is adopted instead: the edits are in the database, so there is nothing to generate', async () => {
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    const applied = structuredClone(fixtureModel);
    applied.tables['t:10']!.name = 'people';
    const { database } = setup(async () => {
      schemaStore
        .getState()
        .adopt({ model: applied, casts, fingerprint: 'f1' });
    });
    await waitFor(() => expect(sqlText()).toMatch(/"people"/));
    database.fingerprint = 'f1';
    act(() => schemaStore.getState().renameColumn('c:10:2', 'state'));
    // adopting dropped the edits, the one just made included, as the handler would not have: it is
    // the handler's job to decide; here it is only seen that what it leaves is what is shown
    expect(
      await screen.findByText(/no changes to generate/),
    ).toBeInTheDocument();
  });

  test('when the check itself fails there is no SQL, and it says so', async () => {
    act(() => schemaStore.getState().renameTable('t:10', 'people'));
    installFakeApi({
      'schema.fingerprint': () => {
        throw new Error('connection lost');
      },
    });
    render(<SqlPanel dbName="app" onSchemaChanged={async () => undefined} />);
    expect(await screen.findByRole('alert')).toHaveTextContent(
      "Couldn't generate the SQL: connection lost",
    );
  });

  test('closes from its button', async () => {
    act(() => uiStore.getState().setSqlPanelOpen(true));
    setup();
    await userEvent.click(
      screen.getByRole('button', { name: 'Close the SQL panel' }),
    );
    expect(uiStore.getState().sqlPanelOpen).toBe(false);
  });
});
